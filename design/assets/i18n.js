  function get() {
    try { return localStorage.getItem(KEY) || FALLBACK; } catch (e) { return FALLBACK; }
  }

  function set(v) {
    try { localStorage.setItem(KEY, v); } catch (e) {}
    document.documentElement.lang = v;
  }

  function lookup(key, locale) {
    var l = LOCALES[locale];
    if (!l) return undefined;
    return key.split(".").reduce(function (acc, part) {
      return acc == null ? undefined : acc[part];
    }, l);
  }

  function interpolate(str, vars) {
    if (!vars) return str;
    return str.replace(/\{(\w+)\}/g, function (m, name) {
      return vars[name] !== undefined ? String(vars[name]) : m;
    });
  }

  function t(key, vars) {
    var cur = get();
    var v = lookup(key, cur);
    if (v === undefined) v = lookup(key, FALLBACK);
    if (v === undefined) {
      // kunci belum dipetakan di locale mana pun: tampilkan nama kunci
      // supaya langsung kelihatan saat mengembangkan bahasa baru.
      return key;
    }
    return interpolate(v, vars);
  }

  function ta(key, vars) { return t(key, vars); }

  /* Terjemahkan DOM: elemen beratribut data-i18n="kunci" (text),
     data-i18n-ph (placeholder), data-i18n-title, data-i18n-aria.
     Elemen tanpa data-i18n dibiarkan apa adanya — kontraknya jelas. */
  function apply(root) {
    var scope = root || document.body;
    scope.querySelectorAll("[data-i18n]").forEach(function (el) {
      var v = t(el.getAttribute("data-i18n"));
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        if (el.type !== "submit" && el.type !== "button") return;
      }
      el.textContent = v;
    });
    scope.querySelectorAll("[data-i18n-ph]").forEach(function (el) {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph")));
    });
    scope.querySelectorAll("[data-i18n-title]").forEach(function (el) {
      el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
    });
    scope.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
      el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
    });
  }

  function toggle() {
    var next = get() === "id" ? "en" : "id";
    set(next);
    return next;
  }

  set(get());

  /* Label nama bahasa dalam bahasa aslinya (endonim). Menambah bahasa baru
     cukup: satu objek di LOCALES + satu baris di sini. */
  var NATIVE = { id: "Bahasa Indonesia", en: "English" };

  function list() {
    return Object.keys(LOCALES).map(function (code) {
      return { code: code, label: NATIVE[code] || code };
    });
  }

  window.POI18N = {
    LOCALES: LOCALES,
    list: list,
    get: get, set: set, t: t, ta: ta, apply: apply, toggle: toggle
  };
